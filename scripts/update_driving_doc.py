def write_doc() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(build_markdown(), encoding="utf-8")
    print(f"updated {OUTPUT}")


def watched_paths() -> list[Path]:
    return [path for path in FILES.values() if path.exists()]


def snapshot(paths: list[Path]) -> dict[Path, int]:
    return {path: path.stat().st_mtime_ns for path in paths}


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the driving stack markdown document")
    parser.add_argument("--watch", action="store_true", help="Continuously rewrite the doc when source files change")
    parser.add_argument("--interval", type=float, default=1.0, help="Watch polling interval in seconds")
    args = parser.parse_args()

    write_doc()
    if not args.watch:
        return 0

    paths = watched_paths()
    previous = snapshot(paths)
    print("watching for drive-stack changes...")
    try:
        while True:
            time.sleep(args.interval)
            current_paths = watched_paths()
            current = snapshot(current_paths)
            if current != previous:
                write_doc()
                previous = current
    except KeyboardInterrupt:
        print("stopped watch mode")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
