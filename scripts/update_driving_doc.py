TOPIC_RE = re.compile(
    r"create_(subscription|publisher)\s*\(\s*[^,]+,\s*[\"']([^\"']+)[\"']",
    re.MULTILINE,
)
NODE_RE = re.compile(r"Node\(.*?package=['\"]([^'\"]+)['\"].*?executable=['\"]([^'\"]+)['\"]", re.DOTALL)
ENTRY_RE = re.compile(r"['\"]([^'\"]+)\s*=\s*([^:'\"]+\.[^:'\"]+:[^'\"]+)['\"]")
CONST_RE = re.compile(r"^([A-Z][A-Z0-9_]+)\s*=\s*(.+)$", re.MULTILINE)


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.exists() else ""


def find_topics(path: Path):
    text = read_text(path)
    result = {"subscription": [], "publisher": []}
    for kind, topic in TOPIC_RE.findall(text):
        result[kind].append(topic)
    return {k: sorted(dict.fromkeys(v)) for k, v in result.items()}


def find_nodes(path: Path):
    text = read_text(path)
    return [(pkg, exe) for pkg, exe in NODE_RE.findall(text)]


def find_entries(path: Path):
    text = read_text(path)
    return ENTRY_RE.findall(text)


def parse_toml(path: Path):
    if not path.exists():
        return {}
    return tomllib.loads(path.read_text(encoding="utf-8"))


def find_consts(path: Path, wanted: list[str]):
    text = read_text(path)
    found = {name: value.strip() for name, value in CONST_RE.findall(text) if name in wanted}
    return found


def rel(path: Path) -> str:
    return str(path.relative_to(ROOT))


def bullets(items: list[str]) -> str:
    if not items:
        return "- None found\n"
    return "".join(f"- `{item}`\n" for item in items)


def pairs(items: list[tuple[str, str]]) -> str:
    if not items:
        return "- None found\n"
    return "".join(f"- `{a}` -> `{b}`\n" for a, b in items)


